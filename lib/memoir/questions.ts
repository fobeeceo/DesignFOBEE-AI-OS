/** 장별 질문. 렌더링에서 매번 filter 하지 않도록 한 번만 만든다. */
export const QUESTIONS_BY_CHAPTER: Record<string, MemoirQuestion[]> = CHAPTERS.reduce(
  (acc, chapter) => {
    acc[chapter.id] = QUESTIONS.filter((q) => q.chapterId === chapter.id);
    return acc;
  },
  {} as Record<string, MemoirQuestion[]>
);

export function getChapter(chapterId: string): MemoirChapter | undefined {
  return CHAPTERS.find((c) => c.id === chapterId);
}

export function getQuestion(questionId: string): MemoirQuestion | undefined {
  return QUESTIONS.find((q) => q.id === questionId);
}

export function chaptersOfPart(partId: MemoirPartId): MemoirChapter[] {
  return CHAPTERS.filter((c) => c.partId === partId);
}
